import React, { useEffect, useState } from 'react'
import { useParams, Link } from 'react-router-dom'
import { api } from '@/services/api/client'
import { ArrowLeft, BrainCircuit, CheckCircle2, XCircle, AlertCircle } from 'lucide-react'

export function RootCausePage() {
  const { id } = useParams<{ id: string }>()
  const [evidenceData, setEvidenceData] = useState<any>(null)

  useEffect(() => {
    async function loadData() {
      try {
        const res = await api.get(`/investigations/${id}/evidence`)
        if (res.data.success) setEvidenceData(res.data.data)
      } catch (e) {}
    }
    if (id) loadData()
  }, [id])

  return (
    <div className="space-y-6">
      <Link to={`/app/investigations/${id}`} className="inline-flex items-center gap-1.5 text-xs font-semibold text-[#2563A6] hover:underline">
        <ArrowLeft className="w-3.5 h-3.5" /> Back to Investigation Workspace
      </Link>

      <div className="bg-white rounded-xl border border-[#E2E8F0] shadow-sm p-6 space-y-4">
        <h1 className="text-xl font-bold text-[#172B4D] flex items-center gap-2">
          <BrainCircuit className="w-5 h-5 text-[#173B67]" /> Competing Root-Cause Analysis
        </h1>
        <p className="text-xs text-[#64748B]">
          Evaluation of mutually competing hypotheses generated by the Root-Cause Investigator Agent.
        </p>

        <div className="space-y-4 pt-2">
          {(evidenceData?.hypotheses || []).map((h: any) => (
            <div key={h.id} className="p-4 rounded-xl border border-[#E2E8F0] bg-[#F5F7FA] space-y-2">
              <div className="flex items-center justify-between">
                <span className="font-bold text-sm text-[#172B4D]">{h.title}</span>
                <span className={`px-2 py-0.5 rounded-full text-[10px] font-bold ${
                  h.status === 'SUPPORTED' ? 'bg-green-100 text-green-800' : 'bg-red-100 text-red-800'
                }`}>
                  {h.status}
                </span>
              </div>
              <p className="text-xs text-slate-600 leading-relaxed">{h.description}</p>
              {h.challenge_rationale && (
                <div className="text-[11px] font-mono text-slate-700 bg-white p-2.5 rounded border border-[#E2E8F0]">
                  Rationale: {h.challenge_rationale}
                </div>
              )}
            </div>
          ))}
        </div>
      </div>
    </div>
  )
}
